# -*- coding: utf-8 -*-
"""Тесты линтера. Запуск: python test_lint.py

Линтер решает, что уйдёт в публикацию, поэтому у него два способа подвести:
пропустить нарушение и забраковать нормальный текст. Проверяем оба.
"""
import sys

import lint

# (текст, должен ли блокироваться)
CASES = [
    # --- обязаны блокироваться ---
    ("Тиша, яка лікує втому", True),
    ("Вилікує безсоння", True),
    ("Лікування застуди", True),
    ("Мікродозинг мухомора", True),
    ("Червоний мухомор у капсулах", True),
    ("Блакитний лотос", True),
    ("Гриби з Карпат", True),
    ("Посилення імунітету", True),
    ("Для боротьби з тривожністю", True),
    ("Курс від депресії", True),
    ("Трійчатка протипаразитна", True),
    ("Антипаразитарний збір", True),
    ("Вирощено в Україні", True),
    ("Гарантований результат", True),
    ("Ефект на 100%", True),
    ("Спокій назавжди", True),
    ("Замість ліків", True),
    ("Профілактика хвороб", True),
    ("Психоактивний ефект", True),

    # --- обязаны проходить ---
    ("Публікуємо як є", False),          # «пуб-лікує-мо»
    ("Ранок без метушні", False),
    ("Фокус, пам'ять, ясність", False),
    ("Розфасовано в Україні", False),
    ("Білі голки на старому дереві", False),
    ("Три хвилини — і готово", False),
    ("Чай кольору осені", False),
    ("Що обрати новачку?", False),
    ("Дякуємо за довіру", False),
    ("Танцюючий гриб", False),
]


def main() -> int:
    failed = []
    for text, must_block in CASES:
        errors, warnings = [], []
        lint.check_text(text, "test", errors, warnings)
        blocked = bool(errors)
        if blocked != must_block:
            failed.append((text, must_block, blocked))

    for text, expected, got in failed:
        kind = "пропустив порушення" if expected else "забракував нормальний текст"
        print(f"  ✖ {kind}: {text!r}")

    print(f"\nперевірок: {len(CASES)} | провалів: {len(failed)}")
    if failed:
        return 1
    print("✅ лінтер працює коректно")
    return 0


if __name__ == "__main__":
    sys.exit(main())
