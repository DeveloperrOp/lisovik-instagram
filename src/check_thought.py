# -*- coding: utf-8 -*-
"""Проверка кадра: закончена ли мысль и выдержан ли голос бренда.

Требование Ярика: каждый кадр должен полностью раскрывать тему и давать
вывод. Один экран — одна законченная мысль, а не красивая фраза, после
которой непонятно, что делать.

Проверять это на глаз бесполезно: через месяц забудется. Поэтому здесь
формальные признаки, которые ловятся машинно.

    claim  утверждение, конкретное
    why    почему так: механизм или причина
    do     что читателю сделать сегодня

Вторая половина файла — правила голоса бренда из скилла
lisovik-article-voice. Каждое из них стоило владельцу переработки текста.

    python check_thought.py content/thoughts.yaml

ОСТОРОЖНО при правке через шелл: последовательность «обратный слэш + b»
в heredoc превращается в настоящий символ backspace, и регулярка молча
начинает искать байт 0x08 вместо границы слова. В этом проекте на это
наступали дважды. Правь файл редактором, а не echo и не heredoc.
"""
import re
import sys
from pathlib import Path

import yaml

# «why» подняли со 150: на 150 знаков помещался только сетап, и мысль
# обрывалась на «им давали печенье» без того, чем дело кончилось.
MAX = {"claim": 46, "why": 230, "do": 60}

# ------------------------------------------------- законченность кадра
# Слайд читают в отрыве от всего остального. У автора контекст есть,
# у читателя — только этот экран. Поэтому кадр, где сказано ЧТО ДЕЛАЛИ
# и не сказано ЧЕМ КОНЧИЛОСЬ, обрывается на полуслове.

# Обстановка: что делали, кому давали, чем мерили
SETUP = re.compile(
    r"\b(давали|приймали|заповнювали|проходили|міряли|крутили|бігли|"
    r"вимірювали|спали|тривало|отримували|порівнювали|дали|замішали)\b", re.I)

# ------------------------------------------------ кадр має продавати
# Аккаунт продающий. Задача кадра — помочь человеку выбрать и купить
# то, что ему подходит, НЕ соврав. Это не то же самое, что отчитаться
# о состоянии доказательной базы.
#
# Я на этом уже обжёгся: взял факт «баллы росли 16 недель» и подал его
# стороной «а потом откатилось». Факт верный, вывод для покупателя —
# «результат ноль». В продающем аккаунте это кадр против покупки.
#
# Возражение как заход брать можно и нужно. Но кадр обязан его СНЯТЬ,
# а не подтвердить.

# Вывод-запрет вместо вывода-действия. «Не бери пробник» по смыслу то же,
# что «бери курс», но читается как «не бери».
DONT = re.compile(r"^\s*«?\s*(не|ні,)\s+\w+", re.I)

# Слова, которыми кадр закрывает продажу вместо того, чтобы вести к ней
# Границы слова обязательны: без них «сумарно» ловилось как «марно»,
# и правило браковало кадр, который как раз продаёт.
KILLS = re.compile(
    r"(\bгірше?,? ніж\b|\bгіршим\b|\bне спрацюв|\bмарно\b|\bмізерн|"
    r"\bнема(є)? сенсу\b|\bне варто брати\b|\bне допомож|"
    r"\bдоказів немає\b|\bнічого не дало\b|\bрізниці не знайшли\b|"
    r"\bне вар(то|те)\b)", re.I)


# ------------------------------------------- кадр не сперечається сам із собою
# Ярик: «надо составлять более понятные НЕ ПРОТИВОРЕЧИВЫЕ вещи».
#
# Я в каждый кадр вставлял оговорку, которая отменяла только что сказанное:
# «показники зрушили, ПЛАЦЕБО-ГРУПИ НЕ БУЛО», «розійшлися, АЛЕ давали
# суміш». Человек читает один экран и не понимает, работает или нет.
#
# Это не честность, а плохой отбор. Оговорка нужна там, где факт с дыркой.
# Значит такой факт просто НЕ ИДЁТ в кадр: в ресёрче их полсотни, среди
# них есть чистые. Правило: один экран — одно утверждение без «но».
CAVEAT = re.compile(
    r"(\bале\b|\bпроте\b|\bщоправда\b|\bутім\b|\bоднак\b|"
    r"плацебо[- ]групи (там )?не було|не дотягнул|вибірка мала|"
    r"група (дуже )?маленька|це не доказ|переносити .{0,20}не можна|"
    r"не зруш|нічого не зрушил)", re.I)


# Исход: чем кончилось. Без него кадр — половина мысли
OUTCOME = re.compile(
    r"(нижч|вищ|кращ|гірш|більш|менш|змінил|не змінил|вийшло|показал|стал|"
    r"лишил|повернул|відкотил|сповз|виріс|зрост|росл|впал|ніж (у|на|в) |"
    r"порівняно з|проти груп|за той самий|так само|"
    # «розійшлися» — про групи, що розділились у цифрах; «не знайшлося» —
    # теж результат, коли робіт немає взагалі. Обидва слова живі й доречні,
    # їх бракувало в першій версії списку
    r"розійш|зійшл|не знайш|знайшлося|не зруш|зруш)", re.I)

# --------------------------------------------------- завершённость мысли

# Обрыв: строка кончается служебным словом, за которым обязано идти
# продолжение. «Чага любить тепло, а не» — читатель ждёт остаток.
DANGLING = re.compile(
    r"\b(і|й|та|а|але|бо|що|щоб|як|коли|якщо|для|без|при|про|над|під|між|"
    r"через|перед|після|до|від|з|із|зі|на|у|в|о|об|по|за|не|ні|це|той|цей)\s*$",
    re.I)

# Действие: без глагола вывод не вывод, а ещё одно утверждение.
# Список пополнялся по факту: первая версия забраковала восемь выводов,
# и все восемь оказались нормальными повелительными глаголами — узок был
# список, а не тексты. Пополняй сюда, а не ослабляй правило.
ACTION = re.compile(
    r"\b(дай|додай|залий|залий|настій|настоюй|проціди|бери|візьми|обери|"
    r"почни|тримай|пий|їж|змели|змішай|розмішай|запий|прибери|постав|"
    r"перестав|перевір|почекай|зачекай|лиши|залиш|роби|зроби|спробуй|"
    r"клади|поклади|заварюй|зберігай|струсни|накрий|насип|вимкни|познач|"
    r"порівняй|порахуй|полічи|знайди|пошукай|подивись|подивися|глянь|дивись|"
    r"понюхай|скуштуй|запиши|признач|відміряй|відклади|розділи|почитай|"
    r"читай|запитай|спитай|напиши|здай|заповни|відзнач|заміси|збий|"
    r"завари|залий|запар|кинь|встав|тримайся|поклич|розломи|надломи|"
    r"випий|замочи|обери|додавай|сипни|обсмаж|підсмаж|звари|перенеси|пересип|приймай|"
    r"перелий|вимкни|увімкни|занеси|познач|не\s+\w+)\b", re.I)

# Разделители частей в extra: вертикальная черта, стрелка, слэш, точка
# с запятой. Запятая сюда НЕ входит намеренно.
#
# Сначала она была в списке — и проверка начала принимать за три шага
# обычную фразу «перший тиждень — пів ложки, далі повна», разрезанную
# по знакам препинания. На кадре это выглядело как три обрывка. То есть
# ложное срабатывание я обменял на ложный пропуск, что хуже: первое
# видно сразу, второе доезжает до аккаунта.
SPLIT = re.compile(r"\s*(?:\||→|;|\s/\s)\s*")

# То, чего в текстах про БАДы быть не может
CLAIMS = re.compile(
    r"\b(лік[уює]|зціл|виліков|терап|хворо|діагноз|симптом|імунітет|"
    r"депрес|тривож|безсон|тиск|цукор\s+у\s+крові|холестерин|запален|"
    r"детокс|очищ[уає]|виводить\s+токсин)", re.I)

DOSAGE = re.compile(r"\b\d+[.,]?\d*\s?(г|мг|мл|грам|міліграм)\b", re.I)

# Пустые слова: занимают экран, не несут ничего
EMPTY = re.compile(
    r"\b(дар природи|сила лісу|натуральний продукт|унікальн|неймовірн|"
    r"справжн[яє] магія|секрет здоров|цілюща сила|чарівн)", re.I)


# ------------------------------------------------------------ голос бренда

# Подлежащее «мы» — текст про нас, а не про читателя
WE = re.compile(r"(?:^|[.!?]\s+|\s)(ми|наш\w*|Лісовик)\b", re.I)

# Служебная подводка: пересказ содержания вместо самого содержания
# «нижче» тут ловится только как подводка — «нижче знайдеш», «нижче буде».
# Раньше правило брало слово целиком, и «нижче оцінювали власну втому»
# помечалось браком, хотя это обычное сравнение, а не отсылка к тексту.
LEADIN = re.compile(
    r"(\bнижче\s+(ми|ти|знайдеш|буде|подано|наведено|розберемо|у таблиці)|"
    r"^нижче\b|\bдалі розберемо\b|\bдалі буде\b|\bми даємо\b|\bпоказуємо\b|"
    r"\bу цій статті\b|\bпо порядку\b|\bрозберемо кожен\b)", re.I)

# Самоподрыв: страх виден в тексте, и покупатель его считывает
HEDGE = re.compile(
    r"\b(даних (поки що )?(немає|недостатньо)|не доведено|"
    r"нічого не обіцяємо|лише наша практика|важко сказати)", re.I)

# Приписывание эффекта продукту
PROMISE = re.compile(
    r"\b(гарантуємо|точно спрацює|безпечно для всіх|побічних немає|"
    r"замінює препарат|клінічно доведено|дослідження це підтверджують)\b", re.I)

# Метафоры, которые в наших текстах уже ловили пустыми
METAPHOR = re.compile(
    r"\b(лотере|драбин|внутрішній будильник|обіцяє історію|грає проти нас)",
    re.I)

# Термины: то, что читатель не встречает в быту
TERM = re.compile(
    r"\b(гериценон\w*|еринацин\w*|кордицепін\w*|вітанолід\w*|вітаферин\w*|"
    r"ганодер\w*|тритерпен\w*|бета-глюкан\w*|полісахарид\w*|фікоціанін\w*|"
    r"хлорофіл\w*|меланін\w*|бетулін\w*|аденозин\w*|міцелі\w*|"
    r"Hericium|Inonotus|Cordyceps|Ganoderma|Withania)", re.I)

# Связка, которой вводят термин
BIND = re.compile(r"(зветься|звуть|називають|тобто|імʼя|на ім|це\s)", re.I)


# ------------------------------------------------------------------ ритм
# §16.8-16.11 скилла голоса. Четыре независимых читателя поставили тексту
# «простота 7/10, людяність 4/10» и сформулировали одинаково: фактура
# человеческая, синтаксис машинный. Все пороги простоты при этом были
# зелёные — ритм не мерил никто.

# Плотность «не»: у нас 1,98-5,27 на 1000 знаков, у живого блога владельца
# 0,41-1,94. Наш минимум выше его максимума — мы строим мысль через
# «не то, а то», потому что так легче показать отличие. Читателю отличие
# не нужно, ему нужен предмет.

# Слова не с той полки: в заголовке кадра читатель встречает их бытовое
# значение, а оно всегда первое
WRONG_SHELF = re.compile(
    r"\b(розчинник|множник|фракці|вісь|підкладк|зона розміну|вихід)\b", re.I)

# Метафоры-действия без факта рядом: «працює множником», «виступає
# каталізатором». Образ есть, вещества и числа нет
EMPTY_ACT = re.compile(
    r"\b(працює|виступає|служить|є)\s+(множник|каталізатор|ключ|мостом|"
    r"драйвер|двигун|фундамент)", re.I)


def rhythm(t: dict) -> list:
    """Претензии по ритму. Гейта на это нигде нет, кроме этого места."""
    bad = []
    blob = " ".join((t.get(f) or "") for f in ("claim", "why", "do"))

    # Порог плотности из скилла снят на СТАТЬЯХ в тысячи знаков. На кадре
    # в 250 знаков одно «не» сразу даёт 4 на тысячу — метрика не переносится.
    # Поэтому здесь абсолютный счёт: три «не» на один экран это уже спор,
    # а не мысль. Одно в возражении и одно в ответе — нормально.
    nots = len(re.findall(r"\bне\b", blob, re.I))
    if nots > 2:
        bad.append(f"«не» {nots} рази на одному екрані — думка будується "
                   f"через заперечення, а не через предмет")

    claim = t.get("claim") or ""
    m = WRONG_SHELF.search(claim)
    if m:
        bad.append(f"слово не з тієї полиці в заголовку: «{m.group(0)}» — "
                   f"читач зустріне його побутове значення першим")

    m = EMPTY_ACT.search(blob)
    if m:
        bad.append(f"метафора-дія без факту: «{m.group(0)}» — постав поруч "
                   f"речовину, число або дію читача")

    # Новые имена в кадре: кадр это один абзац, ≤4
    names = set(x.lower() for x in TERM.findall(blob))
    if len(names) > 4:
        bad.append(f"нових імен у кадрі {len(names)}, ліміт 4")

    # Связка «це/зветься» — не больше двух на кадр
    binds = len(BIND.findall(blob))
    if binds > 2:
        bad.append(f"звʼязок «це / зветься / звуть» {binds}, ліміт 2 на кадр")

    return bad


# ------------------------------------------- зрозуміло навіть дитині
# Ярик: «а також зрозумілий навіть дитині». §16 скилла міряє це на
# статтях у тисячі знаків, і там пороги щільності. На кадрі в 20 слів
# щільність не працює — тут рахунок абсолютний.
#
# TERM вище ловить хімію. Але кадр валить не тільки хімія: «плодові
# тіла», «екстракт», «стандартизований» — це слова з етикетки й з
# лабораторії, дитина їх не знає, а доросла людина на свайпі не
# зупиняється, щоб їх розібрати.
BOOKISH = re.compile(
    r"\b(сполук\w*|плодов\w+\s+тіл\w*|екстракт\w*|стандартизован\w*|"
    r"біодоступн\w*|концентрац\w*|ферментац\w*|метаболіт\w*|штам\w*|"
    r"субстрат\w*|антиоксидант\w*|адаптоген\w*|імуномодул\w*|"
    r"біологічно активн\w*|дієтичн\w+ добавк\w*)", re.I)


def plain(t: dict) -> list:
    """Дитячий тест. Три заміри, усі абсолютні."""
    bad = []
    if t.get("layout") != "poster":
        return bad
    blob = " ".join((t.get(f) or "") for f in ("claim", "why", "do"))

    # 1. Слова не з побуту: разом хімія і книжкові. Ліміт один на кадр,
    #    і той має стояти поруч зі звʼязкою «це / зветься / звуть».
    hard = set(x.lower() for x in TERM.findall(blob))
    hard |= set(m.group(0).lower() for m in BOOKISH.finditer(blob))
    if len(hard) > 1:
        bad.append(f"слів не з побуту {len(hard)} ({', '.join(sorted(hard))}), "
                   f"на плакаті ліміт 1")
    elif hard and not BIND.search(blob):
        bad.append(f"слово не з побуту «{list(hard)[0]}» без звʼязки "
                   f"«це / зветься / звуть» — дитина його не розбере")

    # 2. Довжина речення. На плакаті жорсткіше за статтю: там 13 слів,
    #    тут читають на свайпі.
    for sent in sentences(t):
        n = len(sent.split())
        if n > 10:
            bad.append(f"речення на {n} слів: «{sent[:52]}» — на плакаті 10")

    # 3. Переказ. Головна перевірка §17 скилла: розділ, який не
    #    переказується, читачка не переказує теж. Поле «retell» пише
    #    автор СВОЇМИ словами, і воно не має бути копією тексту кадру:
    #    пʼять слів поспіль збігаються — це не переказ, а копіпаста.
    retell = (t.get("retell") or "").strip()
    if not retell:
        bad.append("немає «retell» — перекажи кадр одним реченням своїми "
                   "словами. Не переказується — читач теж не перекаже")
    else:
        src = re.findall(r"\w+", blob.lower())
        got = re.findall(r"\w+", retell.lower())
        runs = {" ".join(src[i:i + 5]) for i in range(len(src) - 4)}
        if any(" ".join(got[i:i + 5]) in runs for i in range(len(got) - 4)):
            bad.append("«retell» копіює текст кадру пʼятьма словами поспіль "
                       "— це не переказ, а цитата")
    return bad


def sentences(t: dict) -> list:
    """Предложения по полям ОТДЕЛЬНО.

    claim и do точкой не заканчиваются, и при склейке трёх полей все три
    превращались в одно «предложение» на 26 слов — ложное срабатывание.
    """
    out = []
    for f in ("claim", "why", "do"):
        out += [x for x in re.split(r"(?<=[.!?])\s+", t.get(f) or "") if x.split()]
    return out


def voice(t: dict) -> list:
    """Претензии по голосу бренда."""
    bad = []
    for f in ("claim", "why", "do"):
        v = (t.get(f) or "").strip()
        if not v:
            continue
        if WE.search(" " + v):
            bad.append(f"{f}: підмет «ми/наш» — текст про нас, а не про читача")
        for rx, what in ((LEADIN, "службова підводка"), (HEDGE, "самопідрив"),
                         (PROMISE, "обіцянка"), (METAPHOR, "порожня метафора")):
            m = rx.search(v)
            if m:
                bad.append(f"{f}: {what} — «{m.group(0)}»")

    # Термин в первых трёх словах: читателю велят выучить слово сразу,
    # вместо того чтобы подвести к нему действием или предметом
    for f in ("claim", "why"):
        for sent in re.split(r"(?<=[.!?])\s+", t.get(f) or ""):
            for i, w in enumerate(sent.split()[:3]):
                if TERM.search(w):
                    bad.append(f"{f}: термін «{w}» стоїть {i + 1}-м словом — "
                               f"спершу дія або предмет, імʼя останнім")
                    break

    # Термин назвали и не объяснили
    why = t.get("why") or ""
    m = TERM.search(why)
    if m and not BIND.search(why):
        bad.append(f"why: термін «{m.group(0)}» без звʼязки "
                   f"«зветься / звуть / називають»")

    sents = sentences(t)
    if sents:
        longest = max(len(x.split()) for x in sents)
        avg = sum(len(x.split()) for x in sents) / len(sents)
        if longest > 30:
            bad.append(f"найдовше речення {longest} слів, стеля 30")
        if avg > 13:
            bad.append(f"середня довжина речення {avg:.1f} слів, норма 13")
    return bad


def check(t: dict) -> list:
    """Все претензии к кадру. Пусто — мысль закончена и голос выдержан."""
    bad = []

    # Оферта — не мысль, а предложение: ассортимент, директ, сайт. Механику
    # «утверждение → причина → вывод» к ней прикладывать бессмысленно,
    # а вот запреты действуют все.
    if t.get("layout") == "offer":
        blob = " ".join(str(t.get(f, "")) for f in
                        ("claim", "why", "do", "extra"))
        for rx, what in ((CLAIMS, "медична обіцянка"), (DOSAGE, "дозування"),
                         (EMPTY, "порожні слова"), (PROMISE, "обіцянка"),
                         (HEDGE, "самопідрив")):
            m = rx.search(blob)
            if m:
                bad.append(f"{what}: «{m.group(0)}»")
        if not (t.get("do") or "").strip():
            bad.append("оферта без дії: скажи, куди йти")
        parts = [x for x in SPLIT.split(t.get("extra") or "") if x.strip()]
        if len(parts) < 2:
            bad.append("оферті потрібні щонайменше дві позиції в extra")
        return bad

    for f in ("claim", "why", "do"):
        v = (t.get(f) or "").strip()
        if not v:
            bad.append(f"немає «{f}» — думка без нього не закінчена")
            continue
        if len(v) > MAX[f]:
            bad.append(f"{f}: {len(v)} символів, ліміт {MAX[f]}")
        # «а не після», «а не замість» — це закінчене протиставлення,
        # а не обрив. Прийменник тут і є пуантом фрази.
        contrast = re.search(r"\bа?\s*не\s+\w+\s*$", v, re.I)
        if DANGLING.search(v) and not contrast:
            bad.append(f"{f} обривається на службовому слові: «{v[-28:]}»")

    do = (t.get("do") or "").strip()
    if do and not ACTION.search(do):
        bad.append(f"«do» не містить дії — це ще одне твердження, "
                   f"а не висновок: «{do[:40]}»")

    # why должно объяснять, а не повторять claim другими словами
    claim, why = (t.get("claim") or "").lower(), (t.get("why") or "").lower()
    if claim and why:
        cw = set(re.findall(r"\w{5,}", claim))
        ww = set(re.findall(r"\w{5,}", why))
        if cw and len(cw & ww) / len(cw) > 0.7:
            bad.append("«why» переказує «claim» тими самими словами, "
                       "а не пояснює причину")

    # Кадр не должен давать причину НЕ покупать: аккаунт продающий.
    # Границу назвать можно, но она обязана вести к правильному выбору,
    # а не к отказу от покупки.
    if do and DONT.match(do):
        bad.append(f"висновок-заборона замість дії: «{do[:38]}». "
                   f"Скажи те саме дією: не «не бери пробник», а «бери курс»")
    blob_sell = " ".join(str(t.get(f, "")) for f in ("claim", "why", "do"))
    m = KILLS.search(blob_sell)
    if m:
        bad.append(f"кадр закриває продаж: «{m.group(0)}». Той самий факт "
                   f"майже завжди можна повернути стороною, що веде до вибору")

    # Сказано, что делали, и не сказано, чем кончилось — половина мысли.
    # Читатель видит только этот экран и остаётся с вопросом «ну і що?»
    why_t = t.get("why") or ""

    # Кадр, який сам себе спростовує: сказав результат — і тут же відняв
    m = CAVEAT.search(why_t)
    if m and OUTCOME.search(why_t):
        bad.append(f"кадр сперечається сам із собою: «{m.group(0)}» стоїть "
                   f"поруч із результатом. Візьми факт, який не потребує "
                   f"застереження, — у ресьорчі є чисті")

    if SETUP.search(why_t) and not OUTCOME.search(why_t):
        bad.append("думка обірвана: сказано, ЩО РОБИЛИ, і не сказано, "
                   "ЧИМ КІНЧИЛОСЬ — читач бачить лише цей екран")

    blob = " ".join(str(t.get(f, "")) for f in ("claim", "why", "do", "extra"))
    for rx, what in ((CLAIMS, "медична обіцянка"), (DOSAGE, "дозування"),
                     (EMPTY, "порожні слова")):
        m = rx.search(blob)
        if m:
            bad.append(f"{what}: «{m.group(0)}»")

    # раскладкам нужны данные помимо трёх частей
    need = {"steps": 3, "versus": 2, "bullets": 3}
    lay = t.get("layout", "")
    if lay in need:
        parts = [p for p in SPLIT.split(t.get("extra") or "") if p.strip()]
        if len(parts) < need[lay]:
            bad.append(f"розкладка «{lay}» потребує щонайменше "
                       f"{need[lay]} частин в extra, а їх {len(parts)}")
    if lay == "stat" and not re.search(r"\d", t.get("extra", "")):
        bad.append("розкладка «stat» без числа в extra")

    # Плакат: сторис смотрят на свайпе, и абзац там не читает никто.
    # Ярик посмотрел собранный день и сказал «что-то не то». Не то было
    # не в текстах — они как раз стали лучше — а в том, что мы носили
    # лекцию в формате прогрева. Двадцать слов это примерно те две
    # секунды, что кадр живёт, пока палец не ушёл.
    if lay == "poster":
        words = sum(len((t.get(f) or "").split())
                    for f in ("claim", "why", "do"))
        if words > 20:
            bad.append(f"плакат на {words} слів, ліміт 20 — на свайпі "
                       f"прочитається хіба перша половина")
        why_len = len((t.get("why") or "").strip())
        if why_len > 70:
            bad.append(f"на плакаті «why» {why_len} символів, ліміт 70 — "
                       f"це вже абзац, а не рядок під заголовком")

    return bad + voice(t) + rhythm(t) + plain(t)


def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "content/thoughts.yaml")
    if not path.exists():
        print(f"немає файлу {path}")
        return 1
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    thoughts = data["thoughts"] if isinstance(data, dict) else data

    bad_total = 0
    for t in thoughts:
        problems = check(t)
        if problems:
            bad_total += 1
            print(f"\n  ✖ {t.get('key', '?')} — {t.get('topic', '')}")
            for p in problems:
                print(f"      {p}")
    print(f"\nкадрів: {len(thoughts)} | з дефектами: {bad_total}")
    if not bad_total:
        print("✅ кожна думка закінчена, голос витриманий")
    return 2 if bad_total else 0


if __name__ == "__main__":
    sys.exit(main())
