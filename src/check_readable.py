# -*- coding: utf-8 -*-
"""Чи читається текст на кадрі — рахунок, а не «на око».

Ярик 11.09: «дивись, щоб текст скрізь був читабельним». На кадрах, де текст
лягає поверх фотографії, це не питання смаку: літера на світлій банці або на
темному листку просто зникає, і видно це аж на опублікованому пості.

Механіка проста і не залежить від розкладки:

  1. беремо кадр і його підкладку (той самий фон без тексту);
  2. пікселі, які відрізняються, — це і є літери (еталон готується
     тим самим рендером із прихованим текстом, тому збіг піксельний);
  3. для кожного такого пікселя дивимось, ЩО лежить під ним на підкладці;
  4. рахуємо контраст за WCAG між кольором літери й тим, що під нею.

Контраст нижче 3.0 означає, що навіть великий текст тут не читається.
Скрипт повертає частку таких пікселів і найгіршу ділянку кадру.

    python check_readable.py ../out/post_blot
"""
import sys
from pathlib import Path

from PIL import Image

# WCAG дає 4.5 для дрібного тексту й 3.0 для великого. У нас увесь текст
# на кадрі великий — від 25px, заголовки під 80px, — тому поріг 3.0.
# Наш фірмовий оливковий на білому папері дає 3.8: за суворішим порогом
# у брак летіли б і зразкові пости Лісовика.
MIN_CONTRAST = 3.0
# Залишковий шум ~5% дає фоновий візерунок під великими літерами: кадр
# читається, а піксель під штрихом трапляється світлий. Поріг поставлено
# за фактом на семи перевірених очима кадрах — це індикатор, куди глянути,
# а не вирок. Реальні провали (текст на банці, на листку) дають 30-90%.
MAX_BAD_SHARE = 0.06
# Ярик 11.09 показав кадр магнію: середня частка 4.2% — «добре», а
# абзац лежав на темній плямі й не читався. У звіті та ділянка вже
# світилась як «30% проблемних», тільки бракувати за нею я не став.
# Тепер ділянка бракує кадр сама: текст читають абзацами, і достатньо
# одного нечитабельного, щоб кадр був зіпсований.
MAX_CELL_SHARE = 0.12
# Скільки літер має бути в клітинці, щоб частка в ній щось означала.
# При старому мінімумі 40 кадр бракувала клітинка зі 153 пікселями —
# хвіст рядка, де 44 краєві пікселі дають «29% нечитабельних», хоча
# текст чорнилом на білому папері. Абзац, який справді не читається,
# дає сотні й тисячі: провальна клітинка кадру з чашкою — 470 із 479.
MIN_CELL = 400

# Беремо тільки ЯДРА літер — пікселі всередині штриха, не по краю.
# Кадр і підкладка — це той самий рендер, тому поза текстом вони збігаються
# байт у байт: будь-яка різниця і є літера. Поріг тут низький навмисно.
#
# Спроба відсікати край високим порогом різниці провалилась: літера, яка
# зливається з тлом, відрізняється від нього слабо — і просто не потрапляла
# в рахунок. Навмисно зіпсований кадр (заголовок кольором паперу) чекер
# називав чистим. Край відсікає не поріг, а геометрія: див. dense().
DIFF = 8


def gray(px) -> float:
    """Швидка яскравість для пошуку штриха; WCAG-яскравість — у lum()."""
    return 0.299 * px[0] + 0.587 * px[1] + 0.114 * px[2]


def lum(px) -> float:
    """Відносна яскравість за WCAG."""
    c = []
    for v in px[:3]:
        v /= 255.0
        c.append(v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4)
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast(a, b) -> float:
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def dense(fp, bp, x, y, W, H, r=1):
    """Чи це середина штриха, а не край літери й не тонка лінія.

    Ерозія: піксель рахується, тільки якщо ВСІ чотири сусіди на відстані r
    теж відрізняються від підкладки. У краю глифа сусід із боку тла збігається
    з нею — і край відпадає. Так само відпадає лінія-роздільник завтовшки в
    піксель: у неї немає сусіда ні зверху, ні знизу.
    """
    def diff(px, py):
        if not (0 <= px < W and 0 <= py < H):
            return 0
        return abs(gray(fp[px, py]) - gray(bp[px, py]))

    if diff(x, y) < DIFF:
        return False
    return all(diff(px, py) >= DIFF for px, py in
               ((x - r, y), (x + r, y), (x, y - r), (x, y + r)))


def check(frame: Path, bg: Path, step=2):
    fi = Image.open(frame).convert("RGB")
    bi = Image.open(bg).convert("RGB").resize(fi.size)
    fp, bp = fi.load(), bi.load()
    W, H = fi.size

    total = bad = 0
    worst = None
    # кадр ділимо на клітинки, щоб показати, ДЕ саме проблема
    cells = {}
    for y in range(0, H, step):
        for x in range(0, W, step):
            f, b = fp[x, y], bp[x, y]
            if dense(fp, bp, x, y, W, H) is False:
                continue
            total += 1
            c = contrast(f, b)
            key = (int(y / H * 6), int(x / W * 4))
            cell = cells.setdefault(key, [0, 0])
            cell[0] += 1
            if c < MIN_CONTRAST:
                bad += 1
                cell[1] += 1
                if worst is None or c < worst[0]:
                    worst = (c, x, y)
    if not total:
        return {"letters": 0, "bad": 0.0, "worst": None, "cells": []}
    hot = sorted(((v[1] / v[0], k) for k, v in cells.items() if v[0] >= MIN_CELL),
                 reverse=True)[:3]
    return {"letters": total, "bad": bad / total,
            "worst": None if worst is None else round(worst[0], 2),
            "cells": [(f"рядок {k[0] + 1}/6, колонка {k[1] + 1}/4",
                       round(share, 2)) for share, k in hot if share > 0.02]}


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "../out/post_blot")
    # Карусель віддає png, сторіс — jpg; перевіряти треба і те, і те.
    frames = sorted(p for p in root.iterdir()
                    if p.suffix.lower() in (".png", ".jpg")
                    and not p.stem.startswith(("bg_", "0_", "_")))
    if not frames:
        print("немає кадрів у", root)
        return 1
    worst_frames = []
    for f in frames:
        bg = f.parent / "_blank" / f.name
        if not bg.exists():
            print(f"  ? {f.stem}: немає підкладки, пропускаю")
            continue
        r = check(f, bg)
        worst_cell = max((s for _, s in r["cells"]), default=0.0)
        ok = r["bad"] <= MAX_BAD_SHARE and worst_cell <= MAX_CELL_SHARE
        mark = "✔" if ok else "✖"
        print(f"  {mark} {f.stem:22} літер-пікселів {r['letters']:6} | "
              f"нечитабельних {r['bad'] * 100:5.1f}% | найгірший контраст "
              f"{r['worst']}")
        for where, share in r["cells"]:
            print(f"        · {where}: {share * 100:.0f}% проблемних")
        if not ok:
            worst_frames.append(f.stem)
    print()
    if worst_frames:
        print("переробити:", ", ".join(worst_frames))
        return 1
    print("текст читається на всіх кадрах")
    return 0


if __name__ == "__main__":
    sys.exit(main())
